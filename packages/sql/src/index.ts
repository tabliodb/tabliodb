function renderEnumStatements(model: DiagramModel, dialect: SqlDialect): string[] {
  if (dialect !== 'postgresql') {
    return [];
  }

  return Object.values(model.enums).map((databaseEnum) => {
    const enumName = renderQualifiedName(databaseEnum.schema, databaseEnum.name, dialect);
    const values = databaseEnum.values.map(quoteStringLiteral).join(', ');

    // PostgreSQL enum types must be declared before tables can reference them.
    return `CREATE TYPE ${enumName} AS ENUM (${values});`;
  });
}

function renderEnumType(type: ColumnTypeSpec, model: DiagramModel, dialect: SqlDialect): string {
  const databaseEnum = type.enumId ? model.enums[type.enumId] : undefined;

  if (!databaseEnum) {
    return renderTextFallbackType(dialect);
  }

  if (dialect === 'postgresql') {
    return renderQualifiedName(databaseEnum.schema, databaseEnum.name, dialect);
  }

  if (sqlDialectRegistry[dialect].supportsInlineEnum) {
    return `ENUM(${databaseEnum.values.map(quoteStringLiteral).join(', ')})`;
  }

  return renderTextFallbackType(dialect);
}

function renderTextFallbackType(dialect: SqlDialect): string {
  return dialect === 'sqlserver' ? 'NVARCHAR(MAX)' : 'TEXT';
}

function renderCommentStatements(model: DiagramModel, dialect: SqlDialect): string[] {
  if (!sqlDialectRegistry[dialect].supportsSeparateCommentStatements) {
    return [];
  }

  return [
    ...Object.values(model.enums).flatMap((databaseEnum) =>
      databaseEnum.comment
        ? [
            `COMMENT ON TYPE ${renderQualifiedName(databaseEnum.schema, databaseEnum.name, dialect)} IS ${quoteStringLiteral(databaseEnum.comment)};`,
          ]
        : [],
    ),
    ...Object.values(model.tables).flatMap((table) => {
      const tableName = renderTableName(table, dialect);
      const columns = getTableColumns(model, table.id);
      const checks = Object.values(model.checks).filter((check) => check.tableId === table.id);
      const indexes = Object.values(model.indexes).filter((index) => index.tableId === table.id);

      return [
        table.comment ? `COMMENT ON TABLE ${tableName} IS ${quoteStringLiteral(table.comment)};` : null,
        ...columns.map((column) =>
          column.comment
            ? `COMMENT ON COLUMN ${tableName}.${quoteIdentifier(column.name, dialect)} IS ${quoteStringLiteral(column.comment)};`
            : null,
        ),
        ...checks.map((check) =>
          check.comment
            ? `COMMENT ON CONSTRAINT ${quoteIdentifier(check.name, dialect)} ON ${tableName} IS ${quoteStringLiteral(check.comment)};`
            : null,
        ),
        ...indexes.map((index) =>
          index.comment
            ? `COMMENT ON INDEX ${quoteIdentifier(index.name, dialect)} IS ${quoteStringLiteral(index.comment)};`
            : null,
        ),
      ].filter((statement): statement is string => Boolean(statement));
    }),
  ];
}

function renderTableName(table: DatabaseTable, dialect: SqlDialect): string {
  return renderQualifiedName(table.schema, table.name, dialect);
}

function renderQualifiedName(schema: string | undefined, name: string, dialect: SqlDialect): string {
  if (!schema || !sqlDialectRegistry[dialect].supportsSchemas) {
    return quoteIdentifier(name, dialect);
  }

  return `${quoteIdentifier(schema, dialect)}.${quoteIdentifier(name, dialect)}`;
}

function quoteIdentifier(value: string, dialect: SqlDialect): string {
  const quote = sqlDialectRegistry[dialect].identifierQuote;

  if (quote === 'backtick') {
    return `\`${value.replaceAll('`', '``')}\``;
  }

  if (quote === 'bracket') {
    return `[${value.replaceAll(']', ']]')}]`;
  }

  return `"${value.replaceAll('"', '""')}"`;
}

function quoteStringLiteral(value: string): string {
  return `'${value.replaceAll("'", "''")}'`;
}

function renderReferentialAction(action: NonNullable<DatabaseRelationship['onDelete']>): string {
  return action.replaceAll('_', ' ').toUpperCase();
}
