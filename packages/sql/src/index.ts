export type GenerateSqlOptions = {
  dialect: SqlDialect;
  includeComments?: boolean;
};

export type SqlGenerationWarning = {
  code: string;
  message: string;
  target?: {
    id: string;
    type: 'check' | 'column' | 'enum' | 'index' | 'relationship' | 'table';
  };
};

